-- Independent accessory catalog, lifecycle, pricing and store selections.
-- No finished-stock records or prices are copied.

CREATE TABLE `accessory_products` (
  `id` bigint NOT NULL AUTO_INCREMENT,
  `category_id` bigint DEFAULT NULL,
  `supplier_id` bigint DEFAULT NULL,
  `name` varchar(120) NOT NULL,
  `sku` varchar(100) DEFAULT NULL,
  `cover_image` varchar(500) DEFAULT NULL,
  `main_image_media_id` bigint DEFAULT NULL,
  `video_media_id` bigint DEFAULT NULL,
  `detail` longtext,
  `publisher_type` varchar(30) DEFAULT NULL,
  `total_stock` int NOT NULL DEFAULT '0',
  `guide_price` decimal(12,2) DEFAULT NULL,
  `off_shelf_reason` varchar(500) DEFAULT NULL,
  `status` varchar(20) NOT NULL DEFAULT 'warehouse',
  `created_by_account_id` bigint DEFAULT NULL,
  `created_at` datetime NOT NULL DEFAULT CURRENT_TIMESTAMP,
  `updated_at` datetime NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  `spec_dimensions` json DEFAULT NULL,
  `off_shelf_detail` text,
  `off_shelf_at` datetime DEFAULT NULL,
  `source_status` varchar(20) NOT NULL DEFAULT 'warehouse',
  `operations_deleted` tinyint(1) NOT NULL DEFAULT '0',
  `source_off_shelf_reason` varchar(80) DEFAULT NULL,
  `source_off_shelf_detail` varchar(500) DEFAULT NULL,
  `source_off_shelf_at` datetime DEFAULT NULL,
  `attribute_display_order` json DEFAULT NULL,
  `source_block_reason` varchar(32) DEFAULT NULL,
  `selection_generation` bigint NOT NULL DEFAULT '0',
  `operations_invalidated_reason` varchar(200) DEFAULT NULL,
  `operations_invalidated_at` datetime DEFAULT NULL,
  `operations_invalidated_snapshot` json DEFAULT NULL,
  PRIMARY KEY (`id`),
  UNIQUE KEY `uk_accessory_products_sku` (`sku`),
  KEY `fk_accessory_products_category` (`category_id`),
  KEY `fk_accessory_products_supplier` (`supplier_id`),
  KEY `idx_accessory_products_supplier_status` (`supplier_id`,`status`),
  KEY `fk_accessory_products_main_image_media` (`main_image_media_id`),
  KEY `fk_accessory_products_video_media` (`video_media_id`),
  KEY `idx_accessory_source_status` (`source_status`,`operations_deleted`),
  CONSTRAINT `fk_accessory_products_category` FOREIGN KEY (`category_id`) REFERENCES `product_categories` (`id`),
  CONSTRAINT `fk_accessory_products_main_image_media` FOREIGN KEY (`main_image_media_id`) REFERENCES `media_assets` (`id`),
  CONSTRAINT `fk_accessory_products_supplier` FOREIGN KEY (`supplier_id`) REFERENCES `suppliers` (`id`),
  CONSTRAINT `fk_accessory_products_video_media` FOREIGN KEY (`video_media_id`) REFERENCES `media_assets` (`id`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

CREATE TABLE `accessory_product_variants` (
  `id` bigint NOT NULL AUTO_INCREMENT,
  `accessory_product_id` bigint NOT NULL,
  `variant_label` varchar(200) NOT NULL,
  `display_mode` varchar(20) NOT NULL DEFAULT 'single',
  `material` varchar(120) DEFAULT NULL,
  `length_value` varchar(120) DEFAULT NULL,
  `color` varchar(120) DEFAULT NULL,
  `size_value` varchar(120) DEFAULT NULL,
  `stock` int NOT NULL DEFAULT '0',
  `status` varchar(32) NOT NULL DEFAULT 'enabled',
  `created_at` datetime NOT NULL DEFAULT CURRENT_TIMESTAMP,
  `updated_at` datetime NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  `sales_attributes` json DEFAULT NULL,
  `cost_price` decimal(12,2) DEFAULT NULL,
  PRIMARY KEY (`id`),
  UNIQUE KEY `uk_accessory_variant_product_id` (`accessory_product_id`,`id`),
  KEY `idx_accessory_product_variant_product` (`accessory_product_id`,`id`),
  CONSTRAINT `fk_accessory_product_variant_product` FOREIGN KEY (`accessory_product_id`) REFERENCES `accessory_products` (`id`) ON DELETE CASCADE,
  CONSTRAINT `chk_accessory_product_variant_stock` CHECK ((`stock` >= 0))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

