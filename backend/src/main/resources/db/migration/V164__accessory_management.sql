CREATE TABLE `accessory_product_prices` (
  `id` bigint NOT NULL AUTO_INCREMENT,
  `accessory_product_id` bigint NOT NULL,
  `store_level_id` bigint NOT NULL,
  `store_level_name` varchar(120) NOT NULL,
  `variant_label` varchar(200) DEFAULT NULL,
  `price_coefficient` decimal(7,4) NOT NULL,
  `cost_price` decimal(12,2) NOT NULL,
  `price` decimal(12,2) NOT NULL,
  `created_at` datetime NOT NULL DEFAULT CURRENT_TIMESTAMP,
  `updated_at` datetime NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  `price_source` varchar(20) NOT NULL DEFAULT 'manual',
  `source_configuration_id` bigint DEFAULT NULL,
  `sku_id` bigint NOT NULL,
  PRIMARY KEY (`id`),
  UNIQUE KEY `uk_accessory_price_sku_level` (`accessory_product_id`,`sku_id`,`store_level_id`),
  KEY `fk_accessory_product_prices_store_level` (`store_level_id`),
  KEY `idx_accessory_prices_source_configuration` (`source_configuration_id`,`price_source`),
  CONSTRAINT `fk_accessory_price_sku` FOREIGN KEY (`accessory_product_id`, `sku_id`) REFERENCES `accessory_product_variants` (`accessory_product_id`, `id`) ON DELETE CASCADE,
  CONSTRAINT `fk_accessory_prices_source_configuration` FOREIGN KEY (`source_configuration_id`) REFERENCES `accessory_markup_configurations` (`id`),
  CONSTRAINT `fk_accessory_product_prices_product` FOREIGN KEY (`accessory_product_id`) REFERENCES `accessory_products` (`id`) ON DELETE CASCADE,
  CONSTRAINT `chk_accessory_prices_source` CHECK ((((`price_source` = _utf8mb4'auto') and (`source_configuration_id` is not null)) or ((`price_source` = _utf8mb4'manual') and (`source_configuration_id` is null)))),
  CONSTRAINT `chk_accessory_product_prices_coefficient` CHECK ((`price_coefficient` >= 0)),
  CONSTRAINT `chk_accessory_product_prices_values` CHECK (((`cost_price` >= 0) and (`price` >= 0)))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

